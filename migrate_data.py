import os
import sqlite3
import psycopg
from datetime import datetime
from dotenv import load_dotenv

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is missing from .env")

# Read the original local database
source = sqlite3.connect("wallet.db")
source.row_factory = sqlite3.Row

tables = {
    "users": """
        CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE,
            password TEXT,
            balance BIGINT DEFAULT 0,
            account_number TEXT UNIQUE,
            transfer_pin_hash TEXT,
            is_active INTEGER DEFAULT 1
        )
    """,
    "transactions": """
        CREATE TABLE IF NOT EXISTS transactions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sender TEXT,
            receiver TEXT,
            amount BIGINT,
            date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """,
    "admins": """
        CREATE TABLE IF NOT EXISTS admins (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE,
            password_hash TEXT
        )
    """,
    "activity_logs": """
        CREATE TABLE IF NOT EXISTS activity_logs (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT,
            activity TEXT,
            details TEXT,
            date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """
}

columns = {
    "users": "id, username, password, balance, account_number, transfer_pin_hash, is_active",
    "transactions": "id, sender, receiver, amount, date",
    "admins": "id, username, password_hash",
    "activity_logs": "id, username, activity, details, date"
}

try:
    with psycopg.connect(DATABASE_URL) as target:
        with target.cursor() as cursor:

            # Create the destination tables
            for sql in tables.values():
                cursor.execute(sql)

            # Stop if this database already contains records
            for table in tables:
                cursor.execute(f"SELECT COUNT(*) FROM {table}")
                if cursor.fetchone()[0] != 0:
                    raise RuntimeError(
                        f"{table} already contains data. Migration stopped."
                    )

            # Copy all original records
            for table, column_list in columns.items():
                rows = source.execute(
                    f"SELECT {column_list} FROM {table}"
                ).fetchall()

                if rows:
                    data = []

                    for row in rows:
                        values = list(row)

                        if table in ["transactions", "activity_logs"]:
                            if values[-1] is not None:
                                values[-1] = datetime.fromisoformat(values[-1])

                        data.append(tuple(values))

                    placeholders = ", ".join(["%s"] * len(rows[0]))

                    cursor.executemany(
                        f"INSERT INTO {table} ({column_list}) "
                        f"VALUES ({placeholders})",
                        data
                    )

                    cursor.executemany(
                        f"INSERT INTO {table} ({column_list}) "
                        f"VALUES ({placeholders})",
                        [tuple(row) for row in rows]
                    )

                print(f"{table}: {len(rows)} records copied")

            # Preserve the original ID counters
            for table in tables:
                cursor.execute(f"""
                    SELECT setval(
                        pg_get_serial_sequence('{table}', 'id'),
                        GREATEST(COALESCE(MAX(id), 1), 1),
                        MAX(id) IS NOT NULL
                    )
                    FROM {table}
                """)

    print("\nMIGRATION SUCCESSFUL!")

except Exception:
    print("\nMIGRATION FAILED. Check the error above.")
    raise

finally:
    source.close()